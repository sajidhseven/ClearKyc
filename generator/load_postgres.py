
#!/usr/bin/env python3
"""
KYC Compliance Management System
Synthetic CSV -> PostgreSQL Loader

Features:
- Loads all application source tables.
- Automatically handles createdAt and updatedAt timestamps.
- Preserves primary and foreign key relationships.
- Uses ON CONFLICT DO NOTHING for safe re-runs.
- Supports optional truncation.
- Keeps ground_truth.csv OUT of the application database.
- Uses a single transaction for data integrity.

Requirements:
    pip install "psycopg[binary]"

Run:
    python generator/load_postgres.py \
        --input generator/output \
        --database-url "postgresql://kyc:kycpass@localhost:5432/kycdb"
"""

import argparse
import csv
import json
import os

from pathlib import Path
from datetime import datetime, timezone

import psycopg

from psycopg import sql
from psycopg.types.json import Jsonb


# --------------------------------------------------
# CSV HELPERS
# --------------------------------------------------

def rows(folder, name):
    file_path = folder / f"{name}.csv"

    if not file_path.exists():
        raise FileNotFoundError(
            f"Required CSV file not found: {file_path}"
        )

    with file_path.open(
        newline="",
        encoding="utf-8"
    ) as file:
        return list(csv.DictReader(file))


def dt(value):
    if not value:
        return None

    return datetime.fromisoformat(value)


def as_bool(value):
    return str(value).lower() == "true"


# --------------------------------------------------
# DATABASE INSERT HELPER
# --------------------------------------------------

def create_insert_helper(cur):
    """
    Inspects PostgreSQL columns and automatically
    supplies timestamps for createdAt / updatedAt
    columns when present.
    """

    column_cache = {}

    def get_columns(table):

        if table not in column_cache:

            cur.execute(
                """
                SELECT column_name
                FROM information_schema.columns
                WHERE table_schema = 'public'
                AND table_name = %s
                """,
                (table,)
            )

            column_cache[table] = {
                row[0] for row in cur.fetchall()
            }

        return column_cache[table]

    def insert(
        table,
        columns,
        values,
        conflict_columns=("id",)
    ):

        columns = list(columns)
        values = list(values)

        available_columns = get_columns(table)

        # Automatically supply Prisma timestamp fields.
        for timestamp_column in (
            "createdAt",
            "updatedAt"
        ):

            if (
                timestamp_column in available_columns
                and timestamp_column not in columns
            ):

                columns.append(timestamp_column)

        placeholders = [
            sql.Placeholder()
            for _ in values
        ]

        # Timestamp values are generated by PostgreSQL.
        for column in columns[len(values):]:
            placeholders.append(
                sql.SQL("CURRENT_TIMESTAMP")
            )

        query = sql.SQL(
            """
            INSERT INTO {table} ({columns})
            VALUES ({values})
            ON CONFLICT ({conflict_columns})
            DO NOTHING
            """
        ).format(
            table=sql.Identifier(table),

            columns=sql.SQL(", ").join(
                sql.Identifier(c)
                for c in columns
            ),

            values=sql.SQL(", ").join(
                placeholders
            ),

            conflict_columns=sql.SQL(", ").join(
                sql.Identifier(c)
                for c in conflict_columns
            )
        )

        cur.execute(query, values)

    return insert


# --------------------------------------------------
# MAIN LOADER
# --------------------------------------------------

def main():

    parser = argparse.ArgumentParser(
        description="Load KYC synthetic data into PostgreSQL"
    )

    parser.add_argument(
        "--input",
        default="generator/output"
    )

    parser.add_argument(
        "--database-url",
        default=os.getenv("DATABASE_URL")
    )

    parser.add_argument(
        "--truncate",
        action="store_true"
    )

    args = parser.parse_args()

    if not args.database_url:
        raise SystemExit(
            "ERROR: Set DATABASE_URL or pass --database-url"
        )

    folder = Path(args.input)

    if not folder.exists():
        raise SystemExit(
            f"ERROR: Input directory does not exist: {folder}"
        )

    print("\n======================================")
    print(" KYC POSTGRESQL DATA IMPORT")
    print("======================================\n")

    conn = psycopg.connect(args.database_url)

    try:

        with conn:

            with conn.cursor() as cur:

                insert = create_insert_helper(cur)

                # ----------------------------------
                # OPTIONAL TRUNCATION
                # ----------------------------------

                if args.truncate:

                    print("[INFO] Truncating application tables...")

                    cur.execute(
                        """
                        TRUNCATE TABLE
                            "AuditEvent",
                            "Alert",
                            "ReviewCase",
                            "BeneficialOwner",
                            "BusinessEntity",
                            "Verification",
                            "Document",
                            "RiskRating",
                            "CustomerRequirement",
                            "Customer",
                            "KYCRequirement",
                            "CustomerType"
                        CASCADE
                        """
                    )

                # ----------------------------------
                # 1. CUSTOMER TYPES
                # ----------------------------------

                print("[1/11] Loading customer types...")

                for x in rows(folder, "customer_types"):

                    insert(
                        "CustomerType",
                        [
                            "id",
                            "name",
                            "description"
                        ],
                        [
                            x["customer_type_id"],
                            x["name"],
                            x["description"]
                        ]
                    )

                # ----------------------------------
                # 2. KYC REQUIREMENTS
                # ----------------------------------

                print("[2/11] Loading KYC requirements...")

                for x in rows(folder, "kyc_requirements"):

                    insert(
                        "KYCRequirement",
                        [
                            "id",
                            "documentType",
                            "name",
                            "mandatory",
                            "minRiskLevel",
                            "effectiveFrom",
                            "effectiveTo"
                        ],
                        [
                            x["kyc_requirement_id"],
                            x["document_type"],
                            x["requirement_name"],
                            as_bool(x["mandatory"]),
                            {
                                1: "LOW",
                                2: "MEDIUM",
                                3: "HIGH"
                            }.get(
                                int(x["min_risk_level"]),
                                "LOW"
                            ),
                            dt(x["effective_from"]),
                            dt(x["effective_to"])
                        ]
                    )

                # ----------------------------------
                # 3. CUSTOMERS
                # ----------------------------------

                print("[3/11] Loading customers...")

                for x in rows(folder, "customers"):

                    insert(
                        "Customer",
                        [
                            "id",
                            "customerTypeId",
                            "legalName",
                            "email",
                            "phone",
                            "country",
                            "city",
                            "onboardingDate",
                            "state",
                            "declaredRisk"
                        ],
                        [
                            x["customer_id"],
                            x["customer_type_id"],
                            x["legal_name"],
                            x["email"],
                            x["phone"] or None,
                            x["country"],
                            x["city"],
                            dt(x["onboarding_date"]),
                            x["lifecycle_state"],
                            x["declared_risk"]
                        ]
                    )

                # ----------------------------------
                # 4. CUSTOMER REQUIREMENT BRIDGE
                # ----------------------------------

                print("[4/11] Loading customer requirements...")

                for x in rows(folder, "customer_requirement_map"):

                    insert(
                        "CustomerRequirement",
                        [
                            "customerId",
                            "requirementId",
                            "effectiveFrom",
                            "effectiveTo"
                        ],
                        [
                            x["customer_id"],
                            x["kyc_requirement_id"],
                            dt(x["effective_from"]),
                            dt(x["effective_to"])
                        ],
                        conflict_columns=(
                            "customerId",
                            "requirementId"
                        )
                    )

                # ----------------------------------
                # 5. RISK RATINGS
                # ----------------------------------

                print("[5/11] Loading risk ratings...")

                for x in rows(folder, "risk_ratings"):

                    insert(
                        "RiskRating",
                        [
                            "id",
                            "customerId",
                            "level",
                            "score",
                            "reasonCode",
                            "effectiveFrom",
                            "effectiveTo"
                        ],
                        [
                            x["risk_rating_id"],
                            x["customer_id"],
                            x["risk_level"],
                            int(x["score"]),
                            x["reason_code"],
                            dt(x["effective_from"]),
                            dt(x["effective_to"])
                        ]
                    )

                # ----------------------------------
                # 6. DOCUMENTS
                # ----------------------------------

                print("[6/11] Loading documents...")

                for x in rows(folder, "documents"):

                    insert(
                        "Document",
                        [
                            "id",
                            "customerId",
                            "documentType",
                            "documentNumber",
                            "issueDate",
                            "expiryDate",
                            "uploadedAt",
                            "status",
                            "nameMatchStatus",
                            "fileHash"
                        ],
                        [
                            x["document_id"],
                            x["customer_id"],
                            x["document_type"],
                            x["document_number"],
                            dt(x["issue_date"]),
                            dt(x["expiry_date"]),
                            dt(x["uploaded_at"]),
                            x["document_status"],
                            x["name_match_status"],
                            x["file_hash"]
                        ]
                    )

                # ----------------------------------
                # 7. VERIFICATIONS
                # ----------------------------------

                print("[7/11] Loading verifications...")

                for x in rows(folder, "verifications"):

                    insert(
                        "Verification",
                        [
                            "id",
                            "documentId",
                            "status",
                            "verifiedAt",
                            "reviewerId",
                            "method"
                        ],
                        [
                            x["verification_id"],
                            x["document_id"],
                            x["verification_status"],
                            dt(x["verified_at"]),
                            x["reviewer_id"] or None,
                            x["verification_method"]
                        ]
                    )

                # ----------------------------------
                # 8. BUSINESS ENTITIES
                # ----------------------------------

                print("[8/11] Loading business entities...")

                for x in rows(folder, "business_entities"):

                    insert(
                        "BusinessEntity",
                        [
                            "id",
                            "customerId",
                            "registrationNumber",
                            "incorporationDate",
                            "jurisdiction",
                            "status"
                        ],
                        [
                            x["business_entity_id"],
                            x["customer_id"],
                            x["registration_number"],
                            dt(x["incorporation_date"]),
                            x["jurisdiction"],
                            x["entity_status"]
                        ]
                    )

                # ----------------------------------
                # 9. BENEFICIAL OWNERS
                # ----------------------------------

                print("[9/11] Loading beneficial owners...")

                for x in rows(folder, "beneficial_owners"):

                    insert(
                        "BeneficialOwner",
                        [
                            "id",
                            "businessEntityId",
                            "ownerName",
                            "ownershipPct",
                            "isPep",
                            "effectiveFrom",
                            "effectiveTo"
                        ],
                        [
                            x["beneficial_owner_id"],
                            x["business_entity_id"],
                            x["owner_name"],
                            x["ownership_pct"],
                            as_bool(x["is_pep"]),
                            dt(x["effective_from"]),
                            dt(x["effective_to"])
                        ]
                    )

                # ----------------------------------
                # 10. REVIEW CASES
                # ----------------------------------

                print("[10/11] Loading review cases...")

                for x in rows(folder, "review_cases"):

                    insert(
                        "ReviewCase",
                        [
                            "id",
                            "customerId",
                            "openedDate",
                            "dueDate",
                            "closedDate",
                            "status",
                            "resolution",
                            "reviewType"
                        ],
                        [
                            x["review_case_id"],
                            x["customer_id"],
                            dt(x["opened_date"]),
                            dt(x["due_date"]),
                            dt(x["closed_date"]),
                            x["review_status"],
                            x["resolution"] or None,
                            x["review_type"]
                        ]
                    )

                # ----------------------------------
                # 11. ALERTS
                # ----------------------------------

                print("[11/11] Loading alerts...")

                for x in rows(folder, "alerts"):

                    insert(
                        "Alert",
                        [
                            "id",
                            "customerId",
                            "documentId",
                            "reviewCaseId",
                            "type",
                            "triggerDate",
                            "dueDate",
                            "severity",
                            "status"
                        ],
                        [
                            x["alert_id"],
                            x["customer_id"],
                            x["document_id"] or None,
                            x["review_case_id"] or None,
                            x["alert_type"],
                            dt(x["trigger_date"]),
                            dt(x["due_date"]),
                            x["severity"],
                            x["alert_status"]
                        ]
                    )

                # ----------------------------------
                # AUDIT EVENTS
                # ----------------------------------

                print("[FINAL] Loading audit events...")

                for x in rows(folder, "audit_events"):

                    customer_id = (
                        x["entity_id"]
                        if x["entity_type"] == "CUSTOMER"
                        else None
                    )

                    before = (
                        json.loads(x["before_json"])
                        if x["before_json"]
                        else None
                    )

                    after = (
                        json.loads(x["after_json"])
                        if x["after_json"]
                        else None
                    )

                    insert(
                        "AuditEvent",
                        [
                            "id",
                            "customerId",
                            "entityType",
                            "entityId",
                            "eventType",
                            "eventAt",
                            "actorId",
                            "beforeJson",
                            "afterJson"
                        ],
                        [
                            x["audit_event_id"],
                            customer_id,
                            x["entity_type"],
                            x["entity_id"],
                            x["event_type"],
                            dt(x["event_at"]),
                            x["actor_id"],
                            Jsonb(before) if before is not None else None,
                            Jsonb(after) if after is not None else None
                        ]
                    )

        print("\n======================================")
        print(" DATA IMPORT COMPLETED SUCCESSFULLY")
        print("======================================")
        print(
            "Ground truth was intentionally excluded "
            "from the application database."
        )

    except Exception:
        print("\n[ERROR] Import failed. Transaction rolled back.")
        raise

    finally:
        conn.close()


if __name__ == "__main__":
    main()
